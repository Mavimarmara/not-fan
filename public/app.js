// Só as páginas de contas: `following_hashtags.html` lista hashtags e não entra aqui.
const FOLLOWERS_ENTRY = /(^|\/)connections\/followers_and_following\/followers(_\d+)?\.html$/;
const FOLLOWING_ENTRY = /(^|\/)connections\/followers_and_following\/following(_\d+)?\.html$/;
const PROFILE_HREF = /^https?:\/\/(?:www\.)?instagram\.com\/(?:_u\/)?([A-Za-z0-9._]+)\/?$/;
const EXPORT_OWNER = /Gerado por\s+([A-Za-z0-9._]+)\s+em\b|Generated by\s+([A-Za-z0-9._]+)\s+on\b/;
const HREF_ATTR = /<a\b[^>]*\bhref="([^"]+)"/gi;
const ZIP_LOCAL_HEADER = 0x04034b50;
const ZIP_CENTRAL_HEADER = 0x02014b50;
const ZIP_END_OF_CENTRAL_DIRECTORY = 0x06054b50;
const ZIP_STORE = 0;
const ZIP_DEFLATE = 8;

export function extractUsernames(pageHtml) {
  const usernames = [];
  for (const match of pageHtml.matchAll(HREF_ATTR)) {
    const profileMatch = PROFILE_HREF.exec(match[1]);
    if (profileMatch) usernames.push(profileMatch[1].toLowerCase());
  }
  return usernames;
}

function uniqueUsernames(usernames) {
  return [...new Set(usernames)];
}

function ownerFromPage(pageHtml) {
  const match = EXPORT_OWNER.exec(pageHtml);
  const owner = match?.[1] ?? match?.[2];
  return owner ? owner.toLowerCase() : null;
}

function findEndOfCentralDirectory(bytes, view) {
  const earliestOffset = Math.max(0, bytes.length - 22 - 0xffff);
  for (let offset = bytes.length - 22; offset >= earliestOffset; offset -= 1) {
    if (view.getUint32(offset, true) === ZIP_END_OF_CENTRAL_DIRECTORY) return offset;
  }
  throw new Error("O arquivo não é um zip do export do Instagram.");
}

function readZipEntries(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const endOffset = findEndOfCentralDirectory(bytes, view);
  const entryCount = view.getUint16(endOffset + 10, true);
  let cursor = view.getUint32(endOffset + 16, true);
  const entries = [];

  for (let index = 0; index < entryCount; index += 1) {
    if (view.getUint32(cursor, true) !== ZIP_CENTRAL_HEADER) {
      throw new Error("O arquivo não é um zip do export do Instagram.");
    }
    const method = view.getUint16(cursor + 10, true);
    const compressedSize = view.getUint32(cursor + 20, true);
    const filenameLength = view.getUint16(cursor + 28, true);
    const extraLength = view.getUint16(cursor + 30, true);
    const commentLength = view.getUint16(cursor + 32, true);
    const localHeaderOffset = view.getUint32(cursor + 42, true);
    const name = new TextDecoder().decode(bytes.subarray(cursor + 46, cursor + 46 + filenameLength));
    entries.push({ name, method, compressedSize, localHeaderOffset });
    cursor += 46 + filenameLength + extraLength + commentLength;
  }

  return { bytes, view, entries };
}

async function readZipText(archive, entry) {
  const { bytes, view } = archive;
  const headerOffset = entry.localHeaderOffset;
  if (view.getUint32(headerOffset, true) !== ZIP_LOCAL_HEADER) {
    throw new Error("O arquivo não é um zip do export do Instagram.");
  }
  const filenameLength = view.getUint16(headerOffset + 26, true);
  const extraLength = view.getUint16(headerOffset + 28, true);
  const dataStart = headerOffset + 30 + filenameLength + extraLength;
  const compressed = bytes.subarray(dataStart, dataStart + entry.compressedSize);

  if (entry.method === ZIP_STORE) return new TextDecoder().decode(compressed);
  if (entry.method !== ZIP_DEFLATE) {
    throw new Error("O zip usa uma compressão que o navegador não lê.");
  }

  const inflated = compressed.buffer.slice(
    compressed.byteOffset,
    compressed.byteOffset + compressed.byteLength,
  );
  const stream = new Blob([inflated]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
  const textBuffer = await new Response(stream).arrayBuffer();
  return new TextDecoder().decode(textBuffer);
}

async function readSection(archive, entryPattern) {
  const pages = archive.entries
    .filter((entry) => entryPattern.test(entry.name))
    .sort((left, right) => left.name.localeCompare(right.name));

  const usernames = [];
  let owner = null;
  for (const entry of pages) {
    const pageHtml = await readZipText(archive, entry);
    owner = owner ?? ownerFromPage(pageHtml);
    usernames.push(...extractUsernames(pageHtml));
  }
  return { usernames: uniqueUsernames(usernames), owner };
}

export async function loadFollowsReport(zipBytes) {
  const archive = readZipEntries(zipBytes);
  const followers = await readSection(archive, FOLLOWERS_ENTRY);
  const following = await readSection(archive, FOLLOWING_ENTRY);
  const owner = followers.owner ?? following.owner;

  if (!owner) {
    throw new Error("Não encontrei as seções de seguidores/seguindo nesse zip.");
  }

  const followerSet = new Set(followers.usernames);
  const followingSet = new Set(following.usernames);
  return {
    owner,
    followerCount: followers.usernames.length,
    followingCount: following.usernames.length,
    notFollowingBack: following.usernames.filter((username) => !followerSet.has(username)),
    notFollowedBack: followers.usernames.filter((username) => !followingSet.has(username)),
  };
}

function profileItem(username) {
  const item = document.createElement("li");
  const link = document.createElement("a");
  link.href = `https://www.instagram.com/${username}/`;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  link.textContent = `@${username}`;
  item.append(link);
  return item;
}

function renderUserList(listElement, usernames) {
  listElement.replaceChildren();
  if (usernames.length === 0) {
    const item = document.createElement("li");
    item.className = "empty";
    item.textContent = "ninguém";
    listElement.append(item);
    return;
  }
  const fragment = document.createDocumentFragment();
  for (const username of usernames) fragment.append(profileItem(username));
  listElement.append(fragment);
}

function setStatus(message, isError) {
  const status = document.querySelector("#status");
  status.textContent = message;
  status.classList.toggle("is-error", isError);
}

function showReport(report) {
  const result = document.querySelector("#result");
  const filter = document.querySelector("#filter");
  result.hidden = false;
  document.querySelector("#summary").textContent =
    `@${report.owner} · ${report.followerCount} seguidores · ${report.followingCount} seguindo`;

  const paint = () => {
    const query = filter.value.trim().toLowerCase();
    const matchesQuery = (username) => username.includes(query);
    const notFollowingBack = report.notFollowingBack.filter(matchesQuery);
    const notFollowedBack = report.notFollowedBack.filter(matchesQuery);
    document.querySelector("#not-following-back-title").textContent =
      `Você segue e não te segue de volta (${notFollowingBack.length})`;
    document.querySelector("#not-followed-back-title").textContent =
      `Te seguem e você não segue de volta (${notFollowedBack.length})`;
    renderUserList(document.querySelector("#not-following-back"), notFollowingBack);
    renderUserList(document.querySelector("#not-followed-back"), notFollowedBack);
  };

  filter.oninput = paint;
  paint();
}

if (typeof document !== "undefined") {
  const form = document.querySelector("#compare-form");
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const submitButton = form.querySelector("button");
    const exportFile = form.elements.export.files[0];
    submitButton.disabled = true;
    document.querySelector("#result").hidden = true;
    setStatus("Lendo o export…", false);

    try {
      const zipBytes = new Uint8Array(await exportFile.arrayBuffer());
      showReport(await loadFollowsReport(zipBytes));
      setStatus("", false);
    } catch (error) {
      setStatus(error instanceof Error ? error.message : "Não consegui ler o export.", true);
    } finally {
      submitButton.disabled = false;
    }
  });
}
